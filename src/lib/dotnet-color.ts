export function dotnetColor(
  color: Record<string, unknown>,
  fallback: string,
): string {
  const value = color.value;
  if (typeof value === "number" && (Number(color.state) & 2) !== 0)
    return "#" + (value >>> 0).toString(16).padStart(8, "0").slice(-6);
  return known[Number(color.knownColor)] ?? fallback;
}

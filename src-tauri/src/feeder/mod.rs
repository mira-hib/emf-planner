use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FeederType {
    pub name: String,
    pub diameter: String,
    pub data_points: Vec<FeederDataPoint>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FeederDataPoint {
    pub frequency_mhz: f64,
    pub attenuation_db_per_100m: f64,
}

impl FeederType {
    pub fn attenuation_at(&self, frequency_mhz: f64) -> f64 {
        if self.data_points.is_empty() {
            return 0.0;
        }
        if self.data_points.len() == 1 {
            return self.data_points[0].attenuation_db_per_100m;
        }

        let mut below = &self.data_points[0];
        let mut above = self.data_points.last().unwrap();

        for p in &self.data_points {
            if p.frequency_mhz <= frequency_mhz {
                below = p;
            }
            if p.frequency_mhz >= frequency_mhz {
                above = p;
                break;
            }
        }

        if (above.frequency_mhz - below.frequency_mhz).abs() < 1e-9 {
            return below.attenuation_db_per_100m;
        }

        let t = (frequency_mhz - below.frequency_mhz) / (above.frequency_mhz - below.frequency_mhz);
        below.attenuation_db_per_100m + t * (above.attenuation_db_per_100m - below.attenuation_db_per_100m)
    }

    pub fn total_loss(&self, frequency_mhz: f64, length_m: f64) -> f64 {
        self.attenuation_at(frequency_mhz) * length_m / 100.0
    }
}

macro_rules! feeder {
    ($name:expr, $diam:expr, [ $( ($freq:expr, $att:expr) ),* $(,)? ]) => {
        FeederType {
            name: $name.into(),
            diameter: $diam.into(),
            data_points: vec![ $( FeederDataPoint { frequency_mhz: $freq, attenuation_db_per_100m: $att } ),* ],
        }
    };
}

